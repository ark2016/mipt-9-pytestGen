"""Where the generated test file goes and whether it may be replaced."""

from __future__ import annotations

from pathlib import Path

from pytestgen.application.collaborators import ProjectTestFiles
from pytestgen.errors import PytestgenError

_TESTS_DIR = "tests"


def module_stem(module_name: str) -> str:
    return module_name.rsplit(".", 1)[-1]


def default_output(project_root: Path, module_name: str) -> Path:
    """``<project_root>/tests/test_<module>_pytestgen.py``."""
    return project_root / _TESTS_DIR / f"test_{module_stem(module_name)}_pytestgen.py"


def check_writable(files: ProjectTestFiles, output: Path, *, overwrite: bool) -> None:
    """Refuse to replace a file pytestgen did not generate (unless ``overwrite``)."""
    if files.exists(output) and not overwrite and not files.is_generated(output):
        raise PytestgenError(
            f"{output} exists and was not generated by pytestgen; "
            "choose another --output or pass --overwrite"
        )
