"""Render a :class:`TestSuite` into the text of a pytest module (pure, deterministic)."""

from __future__ import annotations

import ast
import builtins
import re
from collections import defaultdict
from collections.abc import Callable, Collection, Mapping, Sequence
from dataclasses import dataclass

from pytestgen.codegen.calls import CallBuilder, UnsupportedCall, default_source
from pytestgen.codegen.imports import ImportSet
from pytestgen.codegen.literals import literal_source
from pytestgen.codegen.split import rename_definition, split_test_functions
from pytestgen.domain.models import (
    CaseOrigin,
    FreeFormTest,
    FunctionInfo,
    ObservationKind,
    OracleVerdict,
    Parameter,
    ParamKind,
    TestCaseSpec,
    TestSuite,
)
from pytestgen.log import get_logger

GENERATED_HEADER = '"""Tests generated by pytestgen'
"""Start of the docstring on top of every generated file (detects files made by pytestgen)."""
_WIDTH = 88
_BODY_INDENT = 4
_BLOCK_SEPARATOR = "\n\n\n"
_RENDERED_KINDS = {ObservationKind.RETURNED, ObservationKind.RAISED}
_SCALARS = (int, float, str, bytes, type(None))
_VARIADIC = {ParamKind.VAR_POSITIONAL, ParamKind.VAR_KEYWORD}


def render_test_module(suite: TestSuite) -> str:
    """Render ``suite`` into a complete pytest module.

    Data-driven cases become ``@pytest.mark.parametrize`` tables (one ``*_returns`` and
    one ``*_raises`` test per function), free-form tests are appended verbatim after
    their imports have been hoisted. Cases the oracle marked suspicious, and cases whose
    observation is not ``RETURNED``/``RAISED`` or has no literal form, are left out.

    Raises:
        ValueError: a case does not match its function's signature, or the result
            does not parse.
        ExtractionError: a free-form test is not valid Python.
    """
    return _ModuleRenderer(suite).render()


def map_test_nodes(suite: TestSuite) -> dict[str, TestCaseSpec | FreeFormTest]:
    """Map the pytest node names of the rendered module back to the items they came from.

    Keys are node ids without the file part: ``test_discount_returns[z3-1]`` for a
    parametrize row (its :class:`TestCaseSpec`), and the top-level name
    (``test_x`` or ``TestX``) for a free-form test (its :class:`FreeFormTest`), after the
    renderer renamed colliding names. Items that are not rendered (suspicious cases,
    unrenderable or duplicate rows) are absent. The suite must be renderable.
    """
    renderer = _ModuleRenderer(suite)
    renderer.render()
    return dict(renderer.nodes)


@dataclass(frozen=True, slots=True)
class _Row:
    """One parametrize row: argument sources, expected value (or exception) and its origin."""

    args: tuple[str, ...]
    outcome: str
    origin: CaseOrigin
    value: object = None
    imports: tuple[tuple[str, str], ...] = ()
    case: TestCaseSpec | None = None


class _Names:
    """Hands out unique module-level names, suffixing ``_2``, ``_3`` on collisions."""

    def __init__(self) -> None:
        self._used: set[str] = set()

    def reserve(self, base: str) -> str:
        name, counter = base, 1
        while name in self._used:
            counter += 1
            name = f"{base}_{counter}"
        self._used.add(name)
        return name


class _ModuleRenderer:
    def __init__(self, suite: TestSuite) -> None:
        self._suite = suite
        self._module = suite.module
        self._calls = CallBuilder(suite.module)
        self._imports = ImportSet(suite.module.module_name)
        self._names = _Names()
        self._blocks: list[str] = []
        self._log = get_logger(__name__)
        self.nodes: dict[str, TestCaseSpec | FreeFormTest] = {}
        """Node name (without file) -> the item rendered as that test."""

    def render(self) -> str:
        self._render_cases()
        self._render_free_tests()
        header = f'{GENERATED_HEADER} for {self._module.module_name}. Review before committing."""'
        imports = self._imports.render()
        parts = [header + ("\n\n" + imports if imports else "")]
        parts.extend(self._blocks)
        text = _BLOCK_SEPARATOR.join(parts).rstrip() + "\n"
        try:
            ast.parse(text)
        except SyntaxError as exc:  # a bug in the renderer, never user input
            raise ValueError(f"generated test module does not parse: {exc}") from exc
        return text

    # ------------------------------------------------------------------ data-driven tests

    def _render_cases(self) -> None:
        by_function = self._group_cases()
        for function in self._module.functions:
            cases = by_function.get(function.qualname)
            if not cases:
                continue
            target = self._calls.target(function)
            if target is None:
                self._log.warning("codegen.skip_function", function=function.qualname)
                continue
            returned = [c for c in cases if c.observation.kind is ObservationKind.RETURNED]
            raised = [c for c in cases if c.observation.kind is ObservationKind.RAISED]
            for build, group in ((self._returns_block, returned), (self._raises_block, raised)):
                block = self._guarded(build, function, target, group) if group else None
                if block:
                    self._blocks.append(block)

    def _guarded(
        self,
        build: Callable[[FunctionInfo, str, Sequence[TestCaseSpec]], str | None],
        function: FunctionInfo,
        target: str,
        cases: Sequence[TestCaseSpec],
    ) -> str | None:
        try:
            return build(function, target, cases)
        except UnsupportedCall as exc:
            self._log.warning("codegen.skip_function", function=function.qualname, reason=str(exc))
            return None

    def _group_cases(self) -> dict[str, list[TestCaseSpec]]:
        known = {fn.qualname for fn in self._module.functions}
        grouped: dict[str, list[TestCaseSpec]] = defaultdict(list)
        for case in self._suite.cases:
            if case.function not in known:
                raise ValueError(f"case refers to unknown function {case.function!r}")
            if (
                case.verdict is not OracleVerdict.SUSPICIOUS
                and case.observation.kind in _RENDERED_KINDS
            ):
                grouped[case.function].append(case)
        return grouped

    def _returns_block(
        self, function: FunctionInfo, target: str, cases: Sequence[TestCaseSpec]
    ) -> str | None:
        columns = _columns(function, cases)
        rows = _dedupe(columns, [self._returned_row(function, columns, c) for c in cases])
        if not rows:
            return None
        values = [row.value for row in rows]
        approx = any(_scan(v)[0] for v in values) and all(_scan(v)[1] for v in values)
        variables = self._variables(function, columns)
        arguments = tuple(variables.values())
        result = _unique("expected", {*arguments, *self._reserved(function)})
        if columns:
            expected = f"pytest.approx({result})" if approx else result
        else:
            expected = f"pytest.approx({rows[0].outcome})" if approx else rows[0].outcome
        if approx:
            self._imports.add_module("pytest")
        body = self._assert_lines(function, target, variables, expected)
        return self._function_block(
            function, "returns", arguments=arguments, result=result, rows=rows, body=body
        )

    def _raises_block(
        self, function: FunctionInfo, target: str, cases: Sequence[TestCaseSpec]
    ) -> str | None:
        columns = _columns(function, cases)
        rows = _dedupe(columns, [self._raised_row(function, columns, c) for c in cases])
        if not rows:
            return None
        variables = self._variables(function, columns)
        arguments = tuple(variables.values())
        result = _unique("exc_type", {*arguments, *self._reserved(function)})
        exception = result if columns else rows[0].outcome
        body = [
            f"with pytest.raises({exception}):",
            *self._statement(function, target, variables, 8),
        ]
        self._imports.add_module("pytest")
        return self._function_block(
            function, "raises", arguments=arguments, result=result, rows=rows, body=body
        )

    def _statement(
        self, function: FunctionInfo, target: str, variables: Mapping[str, str], indent: int
    ) -> list[str]:
        """The call as a statement at column ``indent``, exploded if it exceeds the width."""
        call = self._calls.call(function, target, variables)
        lines = (
            [call]
            if indent + len(call) <= _WIDTH
            else self._calls.exploded_call(function, target, variables)
        )
        return [f"    {line}" for line in lines]

    def _assert_lines(
        self, function: FunctionInfo, target: str, variables: Mapping[str, str], expected: str
    ) -> list[str]:
        """``assert call == expected`` laid out the way ruff format would."""
        call = self._calls.call(function, target, variables)
        comparison = f"{call} == {expected}"
        if _BODY_INDENT + len("assert ") + len(comparison) <= _WIDTH:
            return [f"assert {comparison}"]
        if 2 * _BODY_INDENT + len(comparison) <= _WIDTH:
            return ["assert (", f"    {comparison}", ")"]
        lines = self._statement(function, target, variables, 2 * _BODY_INDENT)
        return ["assert (", *lines, f"    == {expected}", ")"]

    def _function_block(
        self,
        function: FunctionInfo,
        suffix: str,
        *,
        arguments: tuple[str, ...],
        result: str,
        rows: list[_Row],
        body: list[str],
    ) -> str:
        name = self._names.reserve(f"test_{_snake(function.qualname)}_{suffix}")
        self._imports.add_name(self._module.module_name, self._calls.imported_name(function))
        if function.is_async:
            self._imports.add_module("asyncio")
        used_rows = rows if arguments else rows[:1]  # no columns: the row is inlined
        for row in used_rows:
            for module, exception in row.imports:
                self._imports.add_name(module, exception)
        self._register_rows(name, rows, parametrized=bool(arguments))
        lines: list[str] = []
        parameters: list[str] = []
        if arguments:
            parameters = [*arguments, result]
            lines.extend(_parametrize(parameters, rows))
            self._imports.add_module("pytest")
        lines.extend(_signature(name, parameters))
        lines.extend(f"    {line}" for line in body)
        return "\n".join(lines)

    def _register_rows(self, name: str, rows: Sequence[_Row], *, parametrized: bool) -> None:
        if not parametrized:
            if rows[0].case is not None:
                self.nodes[name] = rows[0].case
            return
        for number, row in enumerate(rows, start=1):
            if row.case is not None:
                self.nodes[f"{name}[{row.origin.value}-{number}]"] = row.case

    def _variables(self, function: FunctionInfo, columns: Sequence[str]) -> dict[str, str]:
        """Test variable per parameter, renamed when it would shadow a name the body uses."""
        taken = self._reserved(function)
        variables: dict[str, str] = {}
        for column in columns:
            variables[column] = _unique(column, taken | set(variables.values()))
        return variables

    def _reserved(self, function: FunctionInfo) -> set[str]:
        """Module-level names a test body refers to, which its variables must not shadow."""
        return {self._calls.imported_name(function), "pytest", "asyncio"}

    def _returned_row(
        self, function: FunctionInfo, columns: tuple[str, ...], case: TestCaseSpec
    ) -> _Row | None:
        args = self._argument_sources(function, columns, case)
        if args is None or case.observation.value_repr is None:
            return None
        try:
            value = ast.literal_eval(case.observation.value_repr)
        except (ValueError, SyntaxError, MemoryError, RecursionError):
            value = None
            source = None
        else:
            source = literal_source(value, double_quotes=True)
        if source is None:
            self._log.warning("codegen.skip_case", function=case.function, reason="expected")
            return None
        return _Row(args, source, case.origin, value, case=case)

    def _raised_row(
        self, function: FunctionInfo, columns: tuple[str, ...], case: TestCaseSpec
    ) -> _Row | None:
        args = self._argument_sources(function, columns, case)
        resolved = self._resolve_exception(case.observation.exception_type)
        if resolved is None:
            self._log.warning("codegen.skip_case", function=case.function, reason="exception")
            return None
        if args is None:
            return None
        name, imports = resolved
        return _Row(args, name, case.origin, imports=imports, case=case)

    def _argument_sources(
        self, function: FunctionInfo, columns: tuple[str, ...], case: TestCaseSpec
    ) -> tuple[str, ...] | None:
        """Source of every column; parameters the case leaves out get their default."""
        parameters = {p.name: p for p in function.call_parameters}
        sources = [
            literal_source(case.inputs[c], double_quotes=True)
            if c in case.inputs
            else _omitted_source(parameters[c])
            for c in columns
        ]
        if None in sources:
            self._log.warning("codegen.skip_case", function=case.function, reason="inputs")
            return None
        return tuple(s for s in sources if s is not None)

    def _resolve_exception(
        self, qualified: str | None
    ) -> tuple[str, tuple[tuple[str, str], ...]] | None:
        """Exception expression and the import it needs; builtins are referenced by bare name.

        ``pkg.mod.Outer.Inner`` imports ``Outer`` and is referenced as ``Outer.Inner``.
        """
        if not qualified or not all(part.isidentifier() for part in qualified.split(".")):
            return None
        parts = qualified.split(".")
        builtin = len(parts) == 2 and parts[0] == "builtins"
        if builtin or (len(parts) == 1 and _is_builtin_exception(parts[0])):
            return parts[-1], ()
        own = self._module.module_name.split(".")
        if parts[: len(own)] == own and len(parts) > len(own):
            module, rest = own, parts[len(own) :]
        elif len(parts) == 1:
            module, rest = own, parts
        else:
            # a class is told from a package by its capital letter
            split = next((i for i, p in enumerate(parts[1:], 1) if p[:1].isupper()), -1)
            module, rest = parts[:split], parts[split:]
        return ".".join(rest), ((".".join(module), rest[0]),)

    # ------------------------------------------------------------------ free-form tests

    def _render_free_tests(self) -> None:
        emitted_helpers: set[str] = set()
        for free in self._suite.free_tests:
            parsed = split_test_functions(free.source)
            for statement in parsed.imports:
                self._imports.add_source(statement)
            for helper in parsed.helpers:
                if helper not in emitted_helpers:
                    emitted_helpers.add(helper)
                    self._blocks.append(helper)
            if not parsed.tests:
                self._log.warning("codegen.free_test_without_tests", name=free.name)
            for name, text in parsed.tests:
                unique = self._names.reserve(name)
                self.nodes[unique] = free
                self._blocks.append(
                    text if unique == name else rename_definition(text, name, unique)
                )


# --------------------------------------------------------------------------- layout helpers


def _columns(function: FunctionInfo, cases: Sequence[TestCaseSpec]) -> tuple[str, ...]:
    """Parameters that appear in any case, in signature order.

    A case may leave out a parameter that has a default (or is variadic): the solver
    only mentions the parameters of its branch, so the omitted value is filled in later.
    """
    parameters = {p.name: p for p in function.call_parameters}
    present = {name for case in cases for name in case.inputs}
    unknown = sorted(present - set(parameters))
    if unknown:
        raise ValueError(f"{function.qualname}: inputs for unknown parameters {unknown}")
    columns = tuple(name for name in parameters if name in present)
    for case in cases:
        missing = [
            name
            for name in columns
            if name not in case.inputs and not _has_implicit_value(parameters[name])
        ]
        if missing:
            raise ValueError(f"{function.qualname}: case lacks parameters {missing}")
    return columns


def _has_implicit_value(param: Parameter) -> bool:
    return param.default is not None or param.kind in _VARIADIC


def _omitted_source(param: Parameter) -> str | None:
    """Source of the value a call gets when ``param`` is omitted."""
    if param.kind is ParamKind.VAR_POSITIONAL:
        return "()"
    if param.kind is ParamKind.VAR_KEYWORD:
        return "{}"
    return default_source(param)


def _dedupe(columns: tuple[str, ...], rows: list[_Row | None]) -> list[_Row]:
    """Drop unrenderable and duplicate rows; a table without columns keeps one row."""
    seen: set[tuple[tuple[str, ...], str]] = set()
    kept: list[_Row] = []
    for row in rows:
        if row is None or (row.args, row.outcome) in seen:
            continue
        seen.add((row.args, row.outcome))
        kept.append(row)
    return kept if columns else kept[:1]


def _unique(base: str, taken: Collection[str]) -> str:
    while base in taken:
        base += "_"
    return base


def _snake(qualname: str) -> str:
    text = qualname.replace(".", "_")
    text = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", text)
    text = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", text)
    return re.sub(r"_+", "_", text).strip("_").lower() or "function"


def _is_builtin_exception(name: str) -> bool:
    obj = getattr(builtins, name, None)
    return isinstance(obj, type) and issubclass(obj, BaseException)


def _scan(value: object) -> tuple[bool, bool]:
    """Whether ``value`` holds a float, and whether ``pytest.approx`` can compare it."""
    if isinstance(value, float):
        return True, True
    if type(value) is list or type(value) is tuple:
        items: list[object] = list(value)
    elif type(value) is dict:
        items = list(value.values())
    else:
        return False, isinstance(value, _SCALARS)
    return any(isinstance(i, float) for i in items), all(isinstance(i, _SCALARS) for i in items)


def _parametrize(arguments: Sequence[str], rows: Sequence[_Row]) -> list[str]:
    names = [f'"{name}"' for name in arguments]
    single = f"    ({', '.join(names)}),"
    header = (
        [single]
        if len(single) <= _WIDTH
        else ["    (", *(f"        {n}," for n in names), "    ),"]
    )
    lines = ["@pytest.mark.parametrize(", *header, "    ["]
    for number, row in enumerate(rows, start=1):
        items = [*row.args, row.outcome, f'id="{row.origin.value}-{number}"']
        single = f"        pytest.param({', '.join(items)}),"
        if len(single) <= _WIDTH:
            lines.append(single)
        else:
            lines.append("        pytest.param(")
            lines.extend(f"            {item}," for item in items)
            lines.append("        ),")
    lines.extend(["    ],", ")"])
    return lines


def _signature(name: str, arguments: Sequence[str]) -> list[str]:
    line = f"def {name}({', '.join(arguments)}):"
    if len(line) <= _WIDTH:
        return [line]
    return [f"def {name}(", *(f"    {arg}," for arg in arguments), "):"]
