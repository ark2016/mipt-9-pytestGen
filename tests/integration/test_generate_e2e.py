def run_project_pytest(project: Path) -> subprocess.CompletedProcess[str]:
    """Run the project's whole suite (existing tests plus the generated file)."""
    env = {k: v for k, v in os.environ.items() if not k.startswith(("PYTEST", "COV_CORE"))}
    return subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "--no-header"],
        cwd=project,
        env=env,
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=120,
        check=False,
    )


def written_source(report: GenerationReport) -> str:
    """The generated test file; it must exist and parse."""
    assert report.output_path is not None
    source = report.output_path.read_text(encoding="utf-8")
    ast.parse(source)
    return source


class TestPricingHybrid:
    def test_writes_a_test_file_that_passes_in_the_project(self, pricing: Scenario) -> None:
        source = written_source(pricing.report)
        assert pricing.report.output_path == pricing.project / "tests" / "test_pricing_pytestgen.py"
        assert source.startswith('"""Tests generated by pytestgen')
        result = run_project_pytest(pricing.project)
        assert result.returncode == 0, result.stdout + result.stderr

    def test_coverage_grows_over_the_existing_tests(self, pricing: Scenario) -> None:
        report = pricing.report
        assert report.delta.after.line_percent > report.delta.before.line_percent
        assert report.delta.after.branch_percent > report.delta.before.branch_percent
        assert report.delta.line_gain > 30
        assert {item.function for item in report.delta.per_function} >= {
            "discount",
            "shipping_cost",
        }
        assert report.kept_tests > 0
        assert not report.dropped

    def test_solver_and_model_both_contribute(self, pricing: Scenario) -> None:
        origins = {stats.origin for stats in pricing.report.by_origin}
        assert origins == {CaseOrigin.Z3, CaseOrigin.LLM_SLOT}
        assert pricing.llm.kinds["oracle_review"] >= 1
        assert pricing.llm.kinds["propose_inputs"] >= 1  # validate_promo reads a module constant
        assert any("free_shipping(" in call for call in pricing.llm.reviewed_calls)
        assert pricing.report.llm_usage.requests == sum(pricing.llm.kinds.values())

    def test_free_shipping_boundary_is_reviewed_and_flagged_on_the_unmodified_example(
        self, pricing: Scenario
    ) -> None:
        """The solver picks 101 for `order_total > 100`; boundary inputs add the edge itself."""
        assert any("free_shipping(order_total=100" in call for call in pricing.llm.reviewed_calls)
        (bug,) = [b for b in pricing.report.suspected_bugs if b.function == "free_shipping"]
        assert bug.inputs == {"order_total": 100.0}
        assert bug.observed.endswith("False")
        assert bug.explanation == BOUNDARY_NOTE
        assert len(pricing.llm.suspicious_calls) == 1

    def test_reports_render_as_json_and_markdown(self, pricing: Scenario) -> None:
        report = pricing.report
        data = report_from_json(JsonRenderer().render(report))
        assert data["module"] == "shop.pricing"
        assert data["strategy"] == "hybrid"
        assert data["kept_tests"] == report.kept_tests
        markdown = MarkdownRenderer().render(report)
        assert "shop.pricing" in markdown
        assert "shipping_cost" in markdown


class TestCartFreeForm:
    def test_methods_get_free_form_tests_that_pass(self, cart: Scenario) -> None:
        source = written_source(cart.report)
        for name in ("test_add_item_merges_quantities", "test_remove_item_unknown_name_raises"):
            assert f"def {name}" in source
        assert {stats.origin for stats in cart.report.by_origin} == {
            CaseOrigin.LLM_FREE,
            CaseOrigin.LLM_SLOT,
        }
        assert cart.report.delta.after.line_percent == 100.0
        result = run_project_pytest(cart.project)
        assert result.returncode == 0, result.stdout + result.stderr

    def test_forbidden_test_is_rejected_and_never_written(self, cart: Scenario) -> None:
        dropped = {item.name: item for item in cart.report.dropped}
        rejected = dropped["test_add_item_shells_out"]
        assert rejected.reason is DropReason.INVALID_CODE
        assert "subprocess" in rejected.detail
        assert "subprocess" not in written_source(cart.report)

    def test_failing_test_is_repaired_from_its_traceback(self, cart: Scenario) -> None:
        assert cart.llm.kinds["repair"] == 1
        assert "assert cart.total() == 100.0" in cart.llm.prompts_of("repair")[0]
        source = written_source(cart.report)
        assert "== 85.0" in source
        assert "== 100.0" not in source

    def test_static_method_goes_through_the_solver_path(self, cart: Scenario) -> None:
        assert "Cart.parse_qty" in written_source(cart.report)
        assert not any("Cart.parse_qty" in p for p in cart.llm.prompts_of("write_tests"))


def test_boundary_case_proposed_by_the_model_becomes_a_suspected_bug(
    project: Path, settings: Settings, llm: ScriptedLLMServer
) -> None:
    """The solver cannot read `math.isnan`; the model proposes 100 and the oracle objects."""
    pricing = project / "shop" / "pricing.py"
    text = pricing.read_text(encoding="utf-8")
    text = text.replace("RESERVED_CODES =", "import math\n\nRESERVED_CODES =", 1)
    text = text.replace(
        "    return order_total > 100\n",
        "    if math.isnan(order_total):\n"
        '        raise ValueError("nan")\n'
        "    return order_total > 100\n",
    )
    pricing.write_text(text, encoding="utf-8")

    report = generate(settings, target=pricing, project_root=project, functions=("free_shipping",))

    assert len(report.suspected_bugs) == 1
    bug = report.suspected_bugs[0]
    assert bug.function == "free_shipping"
    assert bug.inputs == {"order_total": 100}
    assert bug.observed.endswith("False")
    assert bug.explanation == BOUNDARY_NOTE
    assert llm.suspicious_calls
    markdown = MarkdownRenderer().render(report)
    assert "free_shipping" in markdown
    assert BOUNDARY_NOTE in markdown
    assert written_source(report)
    assert run_project_pytest(project).returncode == 0


