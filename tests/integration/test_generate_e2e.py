def test_import_failure_is_a_one_line_error(project: Path, settings: Settings) -> None:
    """F4: the user sees the cause, not a traceback excerpt."""
    broken = project / "broken_import.py"
    broken.write_text("import nonexistent_pkg_xyz_123\n", encoding="utf-8")
    with pytest.raises(ModuleImportError) as info:
        generate(settings, target=broken, project_root=project, dry_run=True)
    message = str(info.value)
    assert "\n" not in message
    assert message.startswith("cannot import broken_import: ")
    assert "nonexistent_pkg_xyz_123" in message
