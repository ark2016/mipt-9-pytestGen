def test_golden_module_with_returns_raises_and_free_test() -> None:
    cases = (
        returned("add", {"a": 1, "b": 2}, 3),
        returned("add", {"a": "x", "b": "y"}, "xy", CaseOrigin.LLM_SLOT),
        raised("div", {"a": 1, "b": 0}, "ZeroDivisionError"),
    )
    free_test = free(
        "import pytest\nfrom calc import add\n\ndef test_extra():\n    assert add(0, 0) == 0"
    )
    assert render(*cases, free=(free_test,)) == textwrap.dedent(
        '''\
        """Tests generated by pytestgen for calc. Review before committing."""

        import pytest

        from calc import add, div


        @pytest.mark.parametrize(
            ("a", "b", "expected"),
            [
                pytest.param(1, 2, 3, id="z3-1"),
                pytest.param("x", "y", "xy", id="llm_slot-2"),
            ],
        )
        def test_add_returns(a, b, expected):
            assert add(a, b) == expected


        @pytest.mark.parametrize(
            ("a", "b", "exc_type"),
            [
                pytest.param(1, 0, ZeroDivisionError, id="z3-1"),
            ],
        )
        def test_div_raises(a, b, exc_type):
            with pytest.raises(exc_type):
                div(a, b)


        def test_extra():
            assert add(0, 0) == 0
        '''
    )


