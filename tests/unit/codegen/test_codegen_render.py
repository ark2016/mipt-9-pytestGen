ADD = function("add", param("a"), param("b"))
DIV = function("div", param("a"), param("b"))
HEADER = '"""Tests generated by pytestgen for calc. Review before committing."""\n'


def render(*cases: TestCaseSpec, functions=(ADD, DIV), free: tuple[FreeFormTest, ...] = ()) -> str:
    text = render_test_module(TestSuite(module(tuple(functions)), tuple(cases), free))
    ast.parse(text)
    return text


def free(source: str, name: str = "test_free", fn: str = "add") -> FreeFormTest:
    return FreeFormTest(name=name, function=fn, source=source)


